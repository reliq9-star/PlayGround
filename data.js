export const ROADS = ROAD_PAIRS.map(([a, b, terrain], index) => {
  const from = CITY_BY_ID[a]
  const to = CITY_BY_ID[b]
  const rawDistance = Math.hypot(from.x - to.x, from.y - to.y) * 0.55
  return {
    id: `${a}--${b}`,
    a,
    b,
    terrain,
    ...ROAD_TERRAIN[terrain],
    distance: Math.max(30, Math.round(rawDistance / 5) * 5),
    curve: index % 3 === 0 ? 1 : index % 3 === 1 ? -1 : 0,
  }
})

export function roadsFrom(cityId) {
  return ROADS.filter((road) => road.a === cityId || road.b === cityId)
}

export function otherEnd(road, cityId) {
  return road.a === cityId ? road.b : road.a
}

